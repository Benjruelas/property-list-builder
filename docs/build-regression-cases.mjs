#!/usr/bin/env node
/**
 * Expand legacy one-line steps into structured action/verify/ui steps.
 * Run: node docs/build-regression-cases.mjs
 */

import { writeFileSync } from 'fs'
import { fileURLToPath } from 'url'
import { dirname, join } from 'path'
import { LEGACY_TEST_CASES } from './regression-test-cases.legacy.mjs'
import { expandLegacyCase } from './expand-regression-case.mjs'

const __dirname = dirname(fileURLToPath(import.meta.url))

function formatStep(s) {
  const parts = [JSON.stringify(s.action), JSON.stringify(s.verify)]
  if (s.ui) parts.push(JSON.stringify(s.ui))
  return `      step(${parts.join(', ')}),`
}

function formatCase(c) {
  const stepsBlock = c.steps.map(formatStep).join('\n')
  return `  tc(${JSON.stringify(c.id)}, ${JSON.stringify(c.section)}, ${JSON.stringify(c.title)}, ${JSON.stringify(c.roles)}, ${JSON.stringify(c.viewport)},
    ${JSON.stringify(c.preconditions)},
    [
${stepsBlock}
    ],
    ${JSON.stringify(c.expected)}),`
}

const expanded = LEGACY_TEST_CASES.map(expandLegacyCase)

const out = `/**
 * Manual regression test case definitions for KnockScout.
 * Generated by docs/build-regression-cases.mjs — do not edit by hand.
 * Rebuild: node docs/build-regression-cases.mjs && node docs/generate-regression-html.mjs
 */

import { tc, step, SECTIONS } from './regression-test-schema.mjs'

export { SECTIONS }

export const TEST_CASES = [
${expanded.map(formatCase).join('\n\n')}
]
`

writeFileSync(join(__dirname, 'regression-test-cases.mjs'), out, 'utf8')

const stepCounts = expanded.map((c) => c.steps.length)
console.log(
  `Wrote regression-test-cases.mjs — ${expanded.length} cases,`,
  `${stepCounts.reduce((a, b) => a + b, 0)} total steps`,
  `(avg ${(stepCounts.reduce((a, b) => a + b, 0) / expanded.length).toFixed(1)}/case)`,
)
